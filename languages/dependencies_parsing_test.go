func TestGoModParsing(t *testing.T) {
	t.Run("parse correct go.mod", func(t *testing.T) {
		gma := GoModAnalyser{}
		depRep, err := gma.Analyse("./testdata/go.mod")
		require.NoError(t, err)
		assert.Equal(t, GOLANG, depRep.Language)
		assert.Equal(t, "1.23.1", depRep.LanguageVersion)
		assert.Equal(t, 3, depRep.LanguageVersionLine)
		assert.Equal(t,
			map[Dependency][]int{
				{Name: "github.com/go-errors/errors", Version: "v1.5.1"}:  {6},
				{Name: "github.com/stretchr/testify", Version: "v1.11.1"}: {7},
				{Name: "golang.org/x/mod", Version: "v0.27.0"}:            {8},
			},
			depRep.Dependencies,
		)
		assert.Equal(t,
			map[Dependency][]int{
				{Name: "github.com/davecgh/go-spew", Version: "v1.1.1"}:    {12},
				{Name: "github.com/pmezard/go-difflib", Version: "v1.0.0"}: {13},
				{Name: "gopkg.in/yaml.v3", Version: "v3.0.1"}:              {14},
			},
			depRep.IndirectDependencies,
		)
	})
}

